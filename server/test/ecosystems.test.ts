import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { buildDependencyFindings } from '../src/common/analysis/dependencyFindings';
import { loadDependencyGraph } from '../src/scan-service/deps/loadGraph';
import { buildDirectSetGraph } from '../src/scan-service/deps/lockfileGraph';
import {
  normalizePypiName,
  parseComposerJson,
  parseGemfileLock,
  parseGoMod,
  parsePom,
  parseRequirements,
} from '../src/scan-service/deps/manifestParsers';
import { discoverDependencyFiles } from '../src/scan-service/repo/discoverDependencyFiles';
import { buildPackage } from './support/fakeScanOutputs';

const GO_MOD = `module example.com/app

go 1.21

require github.com/gin-gonic/gin v1.9.0

require (
\tgolang.org/x/net v0.10.0
\tgithub.com/ugorji/go/codec v1.2.11 // indirect
)
`;

const GEMFILE_LOCK = `GEM
  remote: https://rubygems.org/
  specs:
    rails (6.0.0)
      actionpack (= 6.0.0)
    actionpack (6.0.0)

PLATFORMS
  ruby

DEPENDENCIES
  rails (~> 6.0)
  pg

BUNDLED WITH
   2.4.0
`;

const POM = `<project><dependencies>
  <dependency><groupId>org.springframework</groupId><artifactId>spring-core</artifactId><version>5.3.0</version></dependency>
  <dependency><groupId>junit</groupId><artifactId>junit</artifactId><version>4.12</version><scope>test</scope></dependency>
</dependencies></project>`;

describe('manifest parsers', () => {
  it('reads go.mod requirements and skips the ones marked // indirect', () => {
    expect(parseGoMod(GO_MOD).prod).toEqual(['github.com/gin-gonic/gin', 'golang.org/x/net']);
  });

  it('reads the gems named in the Gemfile from Gemfile.lock', () => {
    expect(parseGemfileLock(GEMFILE_LOCK).prod).toEqual(['rails', 'pg']);
  });

  it('reads requirements.txt names, skipping options and comments', () => {
    const text = '# web\nFlask_Login==0.4.0\n-r base.txt\nrequests>=2.0 ; python_version > "3"\n\n--hash=sha256:abc\n';
    expect(parseRequirements(text).prod).toEqual(['flask-login', 'requests']);
    expect(normalizePypiName('Zope.Interface')).toBe('zope-interface');
  });

  it('uses pip-compile "# via" comments to tell direct from indirect packages', () => {
    const text = [
      '# autogenerated by pip-compile',
      'aiohttp==3.9.0',
      '    # via',
      '    #   -r requirements.in',
      '    #   aiohttp-jinja2',
      'yarl==1.9.0',
      '    # via aiohttp',
      'redis==5.0.0  # via -r requirements.in',
      'myapp-lib==1.0',
      '    # via my-app (pyproject.toml)',
    ].join('\n');
    expect(parseRequirements(text).prod).toEqual(['aiohttp', 'redis', 'myapp-lib']);
    expect(parseRequirements(text).parents?.['yarl']).toEqual(['aiohttp']);
    expect(parseRequirements(text).parents?.['aiohttp']).toEqual(['aiohttp-jinja2']);
  });

  it('builds chains for indirect gems from the Gemfile.lock specs tree', () => {
    const graph = buildDirectSetGraph(parseGemfileLock(GEMFILE_LOCK));
    expect(graph.lookup('actionpack', '6.0.0')).toEqual({ isDirect: false, isDev: false, introducedVia: [['rails', 'actionpack']] });
  });

  it('reads pom.xml as group:artifact and treats test scope as dev', () => {
    expect(parsePom(POM)).toEqual({ prod: ['org.springframework:spring-core'], dev: ['junit:junit'] });
  });

  it('reads composer.json without platform packages', () => {
    expect(parseComposerJson({ require: { php: '>=8', 'ext-json': '*', 'Monolog/Monolog': '^2' }, 'require-dev': { 'phpunit/phpunit': '^9' } }))
      .toEqual({ prod: ['monolog/monolog'], dev: ['phpunit/phpunit'] });
  });
});

describe('buildDirectSetGraph', () => {
  const graph = buildDirectSetGraph({ prod: ['Flask'], dev: ['pytest'] }, normalizePypiName);

  it('marks listed packages direct and everything else indirect', () => {
    expect(graph.lookup('flask', '1.0')).toEqual({ isDirect: true, isDev: false, introducedVia: [['flask']] });
    expect(graph.lookup('pytest', '7.0')?.isDev).toBe(true);
    expect(graph.lookup('werkzeug', '0.15')).toMatchObject({ isDirect: false, introducedVia: [] });
    expect(graph.directCount).toBe(2);
  });
});

describe('dependency files on disk', () => {
  let root: string;

  beforeEach(async () => {
    root = await fs.mkdtemp(path.join(os.tmpdir(), 'deps-'));
  });

  afterEach(async () => {
    await fs.rm(root, { recursive: true, force: true });
  });

  it('finds dependency files of every language and skips vendored folders', async () => {
    await fs.mkdir(path.join(root, 'api'));
    await fs.mkdir(path.join(root, 'venv'));
    await fs.writeFile(path.join(root, 'go.mod'), GO_MOD);
    await fs.writeFile(path.join(root, 'api', 'requirements.txt'), 'flask==1.0\n');
    await fs.writeFile(path.join(root, 'venv', 'requirements.txt'), 'ignored==1.0\n');

    const { files } = await discoverDependencyFiles(root, () => {});
    expect(files.map((file) => [path.relative(root, file.path), file.language])).toEqual([
      ['go.mod', 'Go'],
      [path.join('api', 'requirements.txt'), 'Python'],
    ]);
  });

  it('builds a direct/indirect graph for go.mod and none for formats that do not record it', async () => {
    const goMod = path.join(root, 'go.mod');
    const cargoLock = path.join(root, 'Cargo.lock');
    await fs.writeFile(goMod, GO_MOD);
    await fs.writeFile(cargoLock, '');

    const graph = await loadDependencyGraph(goMod);
    expect(graph?.lookup('golang.org/x/net', 'v0.10.0')?.isDirect).toBe(true);
    expect(graph?.lookup('github.com/ugorji/go/codec', 'v1.2.11')?.isDirect).toBe(false);
    expect(await loadDependencyGraph(cargoLock)).toBeUndefined();
  });
});

describe('ecosystem-specific fix guidance', () => {
  it('gives pip commands for a direct Python package', () => {
    const [finding] = buildDependencyFindings([buildPackage({ ecosystem: 'PyPI', name: 'flask', version: '0.12', isDirect: true })]);
    expect(finding?.fixSteps[0]).toContain('pip install "flask>=');
  });

  it('gives go get with a v-prefixed version for Go', () => {
    const [finding] = buildDependencyFindings([buildPackage({ ecosystem: 'Go', name: 'golang.org/x/net', version: 'v0.10.0' })]);
    expect(finding?.fixSteps[0]).toMatch(/^Run: go get golang\.org\/x\/net@v\S+ && go mod tidy$/);
  });

  it('leaves out the direct/indirect risk factor when the file format does not record it', () => {
    const [finding] = buildDependencyFindings([buildPackage({ ecosystem: 'crates.io', name: 'time', isDirect: undefined })]);
    expect(finding?.dependency?.isDirect).toBeUndefined();
    expect(finding?.riskFactors.some((factor) => /direct dependency/i.test(factor))).toBe(false);
    expect(finding?.fixSteps[0]).toContain('cargo update -p time --precise');
  });
});
